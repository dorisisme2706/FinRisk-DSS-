"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const app = read("src/app.js");
const html = read("index.html");
const css = read("assets/styles.css");
const graph = read("src/ambient-graph.js");
let checks = 0;
function check(name, expression) { assert.ok(expression, name); console.log("PASS", name); checks++; }
check("Original two-tier marketing / workspace structure kept", /class="marketing-header"/.test(html) && /class="workspace-bar"/.test(html));
check("Original five marketing links retained", (html.match(/data-overview-target=/g)||[]).length === 5);
check("Mobile menu controls marketing navigation", html.includes('id="product-menu-toggle"') && html.includes('aria-controls="product-nav"'));
check("Mobile menu starts collapsed", html.includes('aria-expanded="false"'));
check("Menu accessible via keyboard", app.includes('event.key === "Escape"') && app.includes('menuButton.focus()'));
check("Menu closes on outside pointer", app.includes('document.addEventListener("pointerdown"'));
check("Menu closes when breakpoint changes", app.includes('narrowHeader.addEventListener("change"'));
check("Marketing section active state accessible", app.includes('aria-current", "location"'));
check("Workspace active page accessible", app.includes('aria-current", "page"'));
check("Overview section scroll accounts for sticky header", app.includes('header?.getBoundingClientRect().height') && app.includes('scrollY + target.getBoundingClientRect().top - offset'));
check("No unnecessary re-render when already in Overview", app.includes('if (!alreadyOverview) render("overview")'));
check("Animation only on changed screens", app.includes('const screenChanged =') && app.includes('if (screenChanged)'));
check("Animation removed on completion", app.includes('content.onanimationend'));
check("Short animation styled", css.includes('finrisk-screen-enter 250ms'));
check("Reduced motion respected", css.includes('.content.screen-enter { animation: none !important; }') && app.includes('reducedMotion.matches ? "instant" : "smooth"'));
check("Tablet/mobile marketing links available when toggled", css.includes('.marketing-header .product-nav.is-open'));
check("Approved palette retained", css.includes('--forest: #003c33;') && css.includes('--leaf: #9fe870;'));
check("Approved canvas animation unchanged", graph.includes('function initAmbientGraph()') && graph.includes('linkDistance: 175'));
check("News retained", app.includes('id="cg-news"'));
check("Roadmap retained", app.includes('PRODUCT ROADMAP · CONCEPT UI'));
console.log(`All ${checks} UI #03 / #04 static checks PASS.`);
